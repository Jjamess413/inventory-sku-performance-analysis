/* Optional developer QA: npm install playwright; npx playwright install chromium
 * Runs only against the local generated dashboard. No browser sessions/accounts.
 */
"use strict";
const fs=require("node:fs"),path=require("node:path"),assert=require("node:assert/strict");
const {pathToFileURL}=require("node:url"),{execFileSync}=require("node:child_process");
const {chromium}=require("playwright");
const root=path.resolve(__dirname,".."), shots=path.join(root,"dashboard/screenshots");
const python=process.env.PORTFOLIO_PYTHON||"python";
const expected=JSON.parse(execFileSync(python,["-c",
 "import sqlite3,json,sys;c=sqlite3.connect('file:'+sys.argv[1]+'?mode=ro',uri=True);c.row_factory=sqlite3.Row;print(json.dumps(dict(c.execute(\"SELECT SUM(revenue_pence) AS sales,SUM(quantity) AS units,COUNT(DISTINCT invoice_no) AS orders,COUNT(DISTINCT sku) AS active FROM v_sales WHERE country='United Kingdom' AND date>='2011-11-01' AND date<'2011-12-01'\").fetchone())))",
 path.join(root,"data/processed/inventory.sqlite")],{encoding:"utf8"}));
const checks={},errors=[],network=[];
let browser;
async function main(){
 const options={headless:true,args:["--no-sandbox","--disable-gpu","--disable-dev-shm-usage"]};
 if(process.env.PORTFOLIO_CHROMIUM_PATH)options.executablePath=process.env.PORTFOLIO_CHROMIUM_PATH;
 browser=await chromium.launch(options);
 const page=await browser.newPage({viewport:{width:1480,height:1150},deviceScaleFactor:1,acceptDownloads:true});
 page.on("pageerror",e=>errors.push(e.message));
 page.on("request",r=>{if(/^https?:/.test(r.url()))network.push(r.url());});
 await page.goto(pathToFileURL(path.join(root,"dashboard/index.html")).href);
 const totals=()=>page.evaluate(()=>{const o=window.portfolio.overview();return {sales:o.sales,units:o.units,orders:o.orders,active:o.active};});
 assert.deepEqual(await totals(),{sales:965554463,units:5263714,orders:18957,active:3789});
 checks.full_period_kpis_reconcile=true;
 fs.mkdirSync(shots,{recursive:true});
 await page.screenshot({path:path.join(shots,"browser-overview.png"),fullPage:true});
 await page.selectOption("#monthFilter","11");
 assert.equal((await totals()).sales,145774224);
 assert.equal((await totals()).units,750081);
 checks.november_filter_reconciles=true;
 await page.selectOption("#countryFilter",{label:"United Kingdom"});
 assert.deepEqual(await totals(),expected);
 checks.month_and_country_match_independent_sql=true;
 await page.click('[data-page="scenario"]');
 assert.equal(await page.locator("#historicalFilters").isVisible(),false);
 assert.deepEqual(await page.locator("#scenarioKpis .kpi-value").allTextContents(),["984","509","1,845","451"]);
 checks.scenario_ignores_historical_date_country_filters=true;
 await page.selectOption("#scenarioAbc","A");
 assert.equal((await page.locator("#scenarioKpis .kpi-value").allTextContents())[0],"346");
 checks.scenario_a_class_reorder_count=true;
 await page.selectOption("#scenarioAbc","all");
 await page.selectOption("#scenarioStatus","Manual review");
 assert.equal((await page.locator("#scenarioKpis .kpi-value").allTextContents())[2],"1,845");
 const suggested=await page.locator("#scenarioRows tr td:nth-child(8)").allTextContents();
 assert(suggested.length>0&&suggested.every(x=>x==="—"));
 checks.manual_review_order_quantities_remain_blank=true;
 await page.locator("#scenarioRows tr").first().click();
 assert(await page.locator("#detailOverlay").isVisible());
 assert((await page.locator("#detailReason").textContent()).includes("Automatic order quantity is blank"));
 await page.keyboard.press("Tab");
 assert.equal(await page.evaluate(()=>document.activeElement.id),"closeDetail");
 await page.keyboard.press("Escape");
 assert.equal(await page.locator("#detailOverlay").isVisible(),false);
 checks.product_details_and_keyboard_close=true;
 const downloadWait=page.waitForEvent("download");
 await page.click("#exportScenario");
 const download=await downloadWait, file=await download.path();
 const exported=fs.readFileSync(file,"utf8");
 assert.equal(exported.trim().split("\n").length,1846);
 assert(exported.includes("SYNTHETIC_SCENARIO"));
 checks.filtered_scenario_export_preserves_labels=true;
 await page.selectOption("#scenarioStatus","all");
 await page.screenshot({path:path.join(shots,"browser-stock-scenario.png"),fullPage:true});
 await page.click('[data-page="sku"]');
 await page.click("#resetFilters");
 await page.fill("#skuSearch","22423");
 assert.equal(await page.locator("#skuRows tr").count(),1);
 assert((await page.locator("#skuRows").innerText()).includes("168,477.87"));
 checks.sku_search_and_revenue_reconcile=true;
 await page.fill("#skuSearch","a-product-that-does-not-exist");
 assert((await page.locator("#skuRows").innerText()).includes("No matching products"));
 checks.empty_search_state=true;
 await page.fill("#skuSearch","");
 await page.selectOption("#skuSort","units");
 assert((await page.locator("#skuRows tr").first().innerText()).startsWith("23166"));
 await page.click("#skuNext");
 assert((await page.locator("#skuPageInfo").innerText()).includes("Page 2"));
 checks.unit_sort_and_pagination=true;
 await page.click("#skuPrev");
 await page.selectOption("#skuSort","sales");
 await page.screenshot({path:path.join(shots,"browser-sku-explorer.png"),fullPage:true});
 await page.click('[data-page="method"]');
 assert((await page.locator("#page-method").innerText()).includes("not an embedded Power BI report"));
 checks.method_and_delivery_status_visible=true;
 await page.click('[data-page="overview"]');
 await page.setViewportSize({width:390,height:844});
 const dimensions=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
 assert(dimensions.scroll<=dimensions.width,"Unexpected mobile body overflow: "+JSON.stringify(dimensions));
 checks.mobile_layout_has_no_body_overflow=true;
 await page.screenshot({path:path.join(require("node:os").tmpdir(),"inventory-mobile-qa.png"),fullPage:true});
 assert.equal(errors.length,0,errors.join("\n"));assert.equal(network.length,0);
 checks.no_javascript_runtime_errors=true;checks.no_external_runtime_requests=true;
 const report={passed:true,checks,executed_in:"Headless Chromium",artifact:"Standalone browser dashboard",
  screenshot_folder:"dashboard/screenshots (not Power BI screenshots)",desktop_powerbi_execution:"Not performed in this browser test"};
 fs.writeFileSync(path.join(root,"reports/dashboard_runtime_validation.json"),JSON.stringify(report,null,2)+"\n");
 console.log(JSON.stringify(report,null,2));await browser.close();
}
main().catch(async e=>{fs.writeFileSync(path.join(root,"reports/dashboard_runtime_validation.json"),JSON.stringify({passed:false,checks,error:e.message,errors},null,2)+"\n");console.error(e);if(browser)await browser.close();process.exit(1);});
